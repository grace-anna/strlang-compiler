#!/usr/bin/env python3
"""Black-box tests. Build first, then: python3 tests/test_compiler.py"""
import json, subprocess, sys, unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BIN=ROOT/("strlang.exe" if sys.platform=="win32" else "strlang")
def compile_source(source):
    p=subprocess.run([str(BIN)],input=source,text=True,capture_output=True,timeout=3)
    if p.returncode: raise AssertionError(f"exit {p.returncode}: {p.stderr}")
    return json.loads(p.stdout)
class Valid(unittest.TestCase):
    def ok(self,s): self.assertTrue(compile_source(s)["ok"],compile_source(s).get("diagnostic"))
    def test_empty(self): self.ok("")
    def test_declaration(self): self.ok('string x = "hi";')
    def test_uninitialized_decl(self): self.ok('string x;')
    def test_assign_after_decl(self): self.ok('string x; x = "ok"; print(x);')
    def test_print_literal(self): self.ok('print("hello");')
    def test_concat_literals(self): self.ok('string x = "a" + "b";')
    def test_concat_identifiers(self): self.ok('string a="a"; string b="b"; string c=a+b;')
    def test_chain(self): self.ok('string x="a"+"b"+"c"+"d";')
    def test_parentheses(self): self.ok('string x=("a"+"b")+"c";')
    def test_reassignment(self): self.ok('string x="a"; x="b";')
    def test_self_assignment(self): self.ok('string x="a"; x=x+"b";')
    def test_empty_string(self): self.ok('string x=""; print(x);')
    def test_newline_escape(self): self.ok(r'string x="a\nb";')
    def test_tab_escape(self): self.ok(r'string x="a\tb";')
    def test_quote_escape(self): self.ok(r'string x="say \"hi\"";')
    def test_slash_escape(self): self.ok(r'string x="C:\\temp";')
    def test_comments(self): self.ok('// comment\nstring x="ok"; // tail\nprint(x);')
    def test_identifier(self): self.ok('string user_name2="x"; print(user_name2);')
    def test_case_sensitive(self): self.assertEqual(compile_source('string name="x"; print(Name);')["diagnostic"]["kind"],"semantic")
    def test_ast(self): self.assertEqual(compile_source('string x="a";')["ast"]["type"],"Program")
    def test_tokens(self): self.assertGreater(len(compile_source('string x="a";')["tokens"]),3)
    def test_symbol_table(self): self.assertEqual(compile_source('string x="a";')["symbolTable"][0]["name"],"x")
    def test_assignment_sets_initialized(self): self.assertTrue(compile_source('string x; x="v";')["symbolTable"][0]["initialized"])
    def test_many_statements(self): self.ok("\n".join(f'string s{i}="v";' for i in range(30)))
class LexicalErrors(unittest.TestCase):
    def err(self,s): self.assertEqual(compile_source(s)["diagnostic"]["kind"],"lexical")
    def test_invalid_escape(self): self.err(r'string x="bad\q";')
    def test_unterminated_string(self): self.err('string x="abc;')
    def test_raw_newline(self): self.err('string x="a\nb";')
    def test_illegal_character(self): self.err('string x="a" @;')
    def test_digit_start(self): self.err('string 2name="a";')
    def test_unicode(self): self.err('string x="hé";')
class SyntaxErrors(unittest.TestCase):
    def err(self,s): self.assertEqual(compile_source(s)["diagnostic"]["kind"],"syntax")
    def test_missing_semicolon_decl(self): self.err('string x="a"')
    def test_missing_semicolon_assignment(self): self.err('string x="a"; x="b"')
    def test_missing_semicolon_print(self): self.err('print("x")')
    def test_missing_expression(self): self.err('string x=;')
    def test_missing_assign(self): self.err('x "a";')
    def test_missing_print_paren(self): self.err('print "x";')
    def test_missing_close_paren(self): self.err('print("x";')
    def test_unknown_statement(self): self.err('while (x);')
    def test_adjacent_expressions(self): self.err('string x="a" "b";')
    def test_trailing_plus(self): self.err('string x="a"+;')
    def test_missing_name(self): self.err('string = "a";')
class SemanticErrors(unittest.TestCase):
    def err(self,s): self.assertEqual(compile_source(s)["diagnostic"]["kind"],"semantic")
    def test_undeclared_read(self): self.err('print(missing);')
    def test_undeclared_assignment(self): self.err('missing="x";')
    def test_duplicate(self): self.err('string x="a"; string x="b";')
    def test_uninitialized_read(self): self.err('string x; print(x);')
    def test_uninitialized_concat(self): self.err('string x; string y=x+"a";')
    def test_declaration_order(self): self.err('string a=b; string b="x";')
    def test_symbol_snapshot(self): self.assertEqual(compile_source('string x; x="ok";')["symbolTable"][0]["initialized"],True)
if __name__=="__main__":
    suite=unittest.defaultTestLoader.loadTestsFromModule(sys.modules[__name__])
    result=unittest.TextTestRunner(verbosity=2).run(suite)
    sys.exit(0 if result.wasSuccessful() else 1)
